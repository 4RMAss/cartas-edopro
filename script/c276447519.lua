--Performapal Clay Breaker (Manga)
--Script: 4RMAss · Anime Server by 4RMAss
local s,id=GetID()
function s.initial_effect(c)
	local e1=Effect.CreateEffect(c)
	e1:SetType(EFFECT_TYPE_FIELD)
	e1:SetCode(EFFECT_UPDATE_ATTACK)
	e1:SetRange(LOCATION_MZONE)
	e1:SetTargetRange(0,LOCATION_MZONE)
	e1:SetCondition(function(e)
		local c=e:GetHandler()
		return c:IsTributeSummoned() and c:GetBattleTarget() and (Duel.IsPhase(PHASE_DAMAGE) or Duel.IsPhase(PHASE_DAMAGE_CAL))
	end)
	e1:SetTarget(function(e,tc) return tc==e:GetHandler():GetBattleTarget() end)
	e1:SetValue(function(e)
		return -500*Duel.GetMatchingGroupCount(function(c) return c:IsFaceup() and c:IsType(TYPE_PENDULUM) end,e:GetHandlerPlayer(),LOCATION_EXTRA,0,nil)
	end)
	c:RegisterEffect(e1)
end
